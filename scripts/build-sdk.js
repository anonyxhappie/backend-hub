import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC_DIR = path.join(ROOT, 'packages', 'sdk', 'src');
const DIST_DIR = path.join(ROOT, 'packages', 'sdk', 'dist');

async function build() {
  const pkg = JSON.parse(await fs.readFile(path.join(ROOT, 'packages', 'sdk', 'package.json'), 'utf8'));
  const errorsSrc = await fs.readFile(path.join(SRC_DIR, 'errors.js'), 'utf8');
  const httpSrc = await fs.readFile(path.join(SRC_DIR, 'http.js'), 'utf8');
  const indexSrc = await fs.readFile(path.join(SRC_DIR, 'index.js'), 'utf8');

  // Concatenate into a single immutable self-contained ESM browser module with zero external imports.
  const stripLocalImports = (src) =>
    src.replace(/^import\s+\{[^}]*\}\s+from\s+['"]\.\/[^'"]+['"];\r?\n?/gm, '');

  const bundle = [
    `// @backend-hub/sdk v${pkg.version} — immutable release artifact. Do not load from a mutable branch or latest URL.`,
    `// Generated by scripts/build-sdk.js`,
    '',
    '// --- errors.js ---',
    errorsSrc.trim(),
    '',
    '// --- http.js ---',
    stripLocalImports(httpSrc).trim(),
    '',
    '// --- index.js ---',
    stripLocalImports(indexSrc).trim(),
    '',
  ].join('\n');

  await fs.mkdir(DIST_DIR, { recursive: true });
  const outFile = path.join(DIST_DIR, `backend-hub-sdk-${pkg.version}.mjs`);
  await fs.writeFile(outFile, bundle, 'utf8');
  console.log(`Built immutable SDK bundle: ${path.relative(ROOT, outFile)}`);
}

build().catch((err) => {
  console.error(err);
  process.exit(1);
});
